package model;

public class Emp {

    private int empNo;
    private String eName;
    private String job;


    public Emp() {

    }


    public int getEmpNo() {
        return empNo;
    }
    public void setEmpNo(int empNo) {
        this.empNo = empNo;
    }

    public String getEName() {
        return eName;
    }
    public void setEName(String eName) {
        this.eName = eName;
    }

    public String getJob() {
        return job;
    }
    public void setJob(String job) {
        this.job = job;
    }
}
